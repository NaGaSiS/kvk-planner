// Detect browser language and apply
(function() {
  const STORAGE_KEY = 'kvk_lang';
  const SUPPORTED = ['en', 'es', 'fr', 'de', 'pt'];

  function detectLang() {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && SUPPORTED.includes(stored)) return stored;
    const nav = (navigator.language || navigator.userLanguage || 'en').split('-')[0].toLowerCase();
    return SUPPORTED.includes(nav) ? nav : 'en';
  }

  window.KVK_LANG = detectLang();
  window.KVK_T = window.KVK_I18N[window.KVK_LANG] || window.KVK_I18N['en'];

  window.t = function(key, replacements) {
    let str = window.KVK_T[key] || window.KVK_I18N['en'][key] || key;
    if (replacements) {
      Object.entries(replacements).forEach(([k, v]) => { str = str.replace('{' + k + '}', v); });
    }
    return str;
  };

  window.setLang = function(lang) {
    if (!SUPPORTED.includes(lang)) return;
    localStorage.setItem(STORAGE_KEY, lang);
    window.KVK_LANG = lang;
    window.KVK_T = window.KVK_I18N[lang] || window.KVK_I18N['en'];
    document.dispatchEvent(new CustomEvent('kvk-lang-change', { detail: { lang } }));
  };

  // Apply lang attribute to html element
  document.documentElement.setAttribute('lang', window.KVK_LANG);
})();
